#!/usr/bin/env node
// detector-contract.mjs — run representative inputs through classify() and
// verify the output CONTRACT (not implementation assumptions):
//
//   - aiGenerated is tri-state: true|false|null. null propagates, never
//     collapses to false; consumers must not read null as human-made.
//   - provenance (toolGuess/pipeline/provenance) is orthogonal to generation:
//     a tool can be identified while authorship stays undetermined.
//   - hosting alone NEVER yields aiGenerated=true — not even on a generator's
//     own artifact domain (publish/import/manual-edit != generation).
//   - aiGenerated=true requires per-item generation evidence (G-tier hit in ev).
//   - aiGenerated=false requires human-side evidence (H-tier hit in ev).
//   - production method (React stack / raster image) alone never proves AI.
//   - a page that USES a model ("Powered by GPT-4") is not generated by it.
//
// Representative inputs (real dataset files + synthetic fixtures):
//   A. gamma-hosted page (badge+config+DOM present) -> provenance=gamma,
//      authorship still undetermined: uncertain + null
//   B. framer site      -> provenance=framer, uncertain + null (not human)
//   C. hand-written React/Tailwind SPA             -> uncertain + null
//   D. websim artifact (in-artifact globals)        -> ai_confirmed + true
//   E. human baseline   -> human_likely or uncertain, never ai
//   F. bare URL         -> uncertain + null
//   G. pitch.com URL    -> uncertain + null
//   H. vercel.app host  -> uncertain + null
//   I. "Powered by GPT-4" product page              -> uncertain + null
//   J. claude.site artifact URL                     -> uncertain + null
//   K. gamma.app root                               -> toolpage
//   L. created.app app                              -> uncertain + null
//   M/N. generation-only surfaces (vusercontent,    -> uncertain + null
//        chat.z.ai) still provenance only
//
// Usage: node scripts/detector-contract.mjs
import { readFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { classify } from './detector-eval.mjs';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const DS = path.join(ROOT, 'dataset');

function firstMeta(dir, pred = () => true) {
  const m = path.join(DS, dir, 'metadata.jsonl');
  if (!existsSync(m)) return null;
  for (const line of readFileSync(m, 'utf8').split('\n')) {
    if (!line.trim()) continue;
    try {
      const r = JSON.parse(line);
      if (r.file && /\.html$/.test(r.file) && pred(r)) {
        const fp = path.join(DS, dir, r.file);
        if (existsSync(fp) && (r.bytes || 0) < 12_000_000)
          return { file: r.file, url: r.pageUrl || '', html: readFileSync(fp, 'utf8') };
      }
    } catch {}
  }
  return null;
}

const cases = [];
const push = (name, input, expect) => cases.push({ name, input, expect });

// A. gamma-hosted artifact — host/badge/DOM prove the Gamma PIPELINE only.
//    Generation of this doc's design/text stays undetermined (import/manual
//    paths exist) -> uncertain + aiGenerated null, provenance confirmed.
{
  const g = firstMeta('gamma', r => /\.gamma\.site/.test(r.pageUrl || ''));
  if (g) push('A. gamma-hosted page (provenance only)', { url: g.url, html: g.html },
    { verdict: 'uncertain', aiGeneratedNull: true, provenanceTool: 'gamma', scopeDesign: 'unknown' });
}
// B. framer site — designer-tool hosting proves neither human nor AI.
{
  const fr = firstMeta('framer');
  if (fr) push('B. framer site (designer tool)', { url: fr.url, html: fr.html },
    { verdictIn: ['uncertain', 'human_likely'], aiGeneratedNotTrue: true, provenanceTool: 'framer' });
}
// C. synthetic hand-written React/Tailwind/Lucide SPA — no markers
{
  const html = `<!doctype html><html><head><title>My Portfolio</title></head><body>
<div id="root"></div>
<script type="module" src="/assets/index-a1b2c3.js"></script>
<div class="max-w-6xl mx-auto px-6 rounded-lg">
<svg class="lucide lucide-arrow" stroke-linecap="round" stroke-width="2"></svg>
</div></body></html>`;
  push('C. hand-written React/Tailwind SPA (no markers)', { url: 'https://jane-doe.dev/', html },
    { verdict: 'uncertain', aiGeneratedNull: true });
}
// D. websim artifact — in-artifact generator globals are per-item generation
//    evidence (the artifact itself carries websim runtime plumbing).
{
  const w = firstMeta('websim', r => /__websim/.test(readFileSync(path.join(DS, 'websim', r.file), 'utf8')));
  if (w) push('D. websim artifact (in-artifact globals)', { url: w.url, html: w.html },
    { verdict: 'ai_confirmed', aiGenerated: true, scopeDesign: 'ai', scopeText: 'unknown' });
}
// E. human baseline / deckgallery
{
  const h1 = firstMeta('human-baseline') || firstMeta('deckgallery');
  if (h1) push('E. human baseline page', { url: h1.url, html: h1.html },
    { verdictIn: ['human_likely', 'uncertain'], aiGeneratedNotTrue: true });
}
// F. bare unknown URL, no content
push('F. bare URL no content', { url: 'https://example.org/', html: '' },
  { verdict: 'uncertain', aiGeneratedNull: true });
// G. pitch.com deck URL — provenance confirmed, authorship undetermined
push('G. pitch.com deck URL only', { url: 'https://pitch.com/public/abc123', html: '' },
  { verdict: 'uncertain', aiGeneratedNull: true, provenanceTool: 'pitch' });
// H. generic hosts are NOT evidence (no provenance either)
push('H. vercel.app generic host', { url: 'https://my-app.vercel.app/', html: '' },
  { verdict: 'uncertain', aiGeneratedNull: true, provenanceNull: true });
// I. "Powered by GPT-4" — the page USES a model; not generated BY it
{
  const html = `<!doctype html><html><body><h1>Acme Support Bot</h1>
<p>Powered by GPT-4. Built by the Acme team.</p></body></html>`;
  push('I. "Powered by GPT-4" product page', { url: 'https://acme.example.com/', html },
    { verdict: 'uncertain', aiGeneratedNull: true });
}
// J. claude.site/artifacts — Claude artifact surface, provenance only
push('J. claude.site artifact URL', { url: 'https://claude.site/artifacts/1229a009-df4e-406e-9a5e-eed22f353844', html: '' },
  { verdict: 'uncertain', aiGeneratedNull: true, provenanceTool: 'claude-artifact' });
// K. gamma.app marketing root — tool page, not an artifact
push('K. gamma.app root (tool page)', { url: 'https://gamma.app/', html: '' },
  { verdict: 'toolpage', provenanceTool: 'gamma-toolpage' });
// L. created.app (Anything) published app — provenance only
push('L. created.app published app', { url: 'https://myapp.created.app/', html: '' },
  { verdict: 'uncertain', aiGeneratedNull: true, provenanceTool: 'anything' });
// M. vusercontent.net — generation-only surface in practice, still provenance
push('M. vusercontent.net preview host', { url: 'https://preview-abc123.vusercontent.net/', html: '' },
  { verdict: 'uncertain', aiGeneratedNull: true, provenanceTool: 'v0' });
// N. chat.z.ai slide-agent path — surface marks the pipeline, not a record
push('N. chat.z.ai slide space URL', { url: 'https://chat.z.ai/space/abc123-ppt', html: '' },
  { verdict: 'uncertain', aiGeneratedNull: true, provenanceTool: 'zai-slides' });

let fail = 0;
for (const c of cases) {
  const r = classify(c.input);
  const checks = [];
  if (c.expect.verdict) checks.push([r.verdict === c.expect.verdict, `verdict=${r.verdict} want ${c.expect.verdict}`]);
  if (c.expect.verdictIn) checks.push([c.expect.verdictIn.includes(r.verdict), `verdict=${r.verdict} want ${c.expect.verdictIn.join('|')}`]);
  if ('aiGenerated' in (c.expect)) checks.push([r.aiGenerated === c.expect.aiGenerated, `aiGenerated=${r.aiGenerated}`]);
  if (c.expect.aiGeneratedNull) checks.push([r.aiGenerated === null, `aiGenerated=${r.aiGenerated} want null`]);
  if (c.expect.aiGeneratedNotTrue) checks.push([r.aiGenerated !== true, `aiGenerated=${r.aiGenerated} want !true`]);
  if (c.expect.provenanceTool) checks.push([r.provenance?.tool === c.expect.provenanceTool, `provenance.tool=${r.provenance?.tool} want ${c.expect.provenanceTool}`]);
  if (c.expect.provenanceNull) checks.push([r.provenance === null, `provenance=${JSON.stringify(r.provenance)} want null`]);
  if (c.expect.scopeDesign) checks.push([r.scope?.design === c.expect.scopeDesign, `scope.design=${r.scope?.design}`]);
  if (c.expect.scopeText) checks.push([r.scope?.text === c.expect.scopeText, `scope.text=${r.scope?.text}`]);
  // contract invariants (all cases):
  checks.push([r.aiGenerated === true || r.aiGenerated === false || r.aiGenerated === null, `aiGenerated must be tri-state, got ${r.aiGenerated}`]);
  checks.push([r.aiGenerated !== true || r.ev.some(e => /^G/.test(e)), 'aiGenerated=true requires a G: evidence line']);
  checks.push([r.aiGenerated !== false || r.ev.some(e => /^H:/.test(e)), 'aiGenerated=false requires an H: evidence line']);
  checks.push([r.verdict !== 'ai_confirmed' && r.verdict !== 'ai_likely' || r.aiGenerated === true, `verdict ${r.verdict} must map to aiGenerated=true`]);
  const ok = checks.every(([p]) => p);
  console.log(`${ok ? 'PASS' : 'FAIL'}  ${c.name}`);
  console.log(`      -> verdict=${r.verdict} aiGenerated=${r.aiGenerated} tool=${r.toolGuess} prov=${JSON.stringify(r.provenance)} pipe=${r.pipeline} conf=${r.conf}`);
  if (r.scope) console.log(`      scope=${JSON.stringify(r.scope)}`);
  for (const [p, msg] of checks) if (!p) console.log(`      x ${msg}`);
  if (!ok) fail++;
}
console.log(`\n${cases.length - fail}/${cases.length} contract checks passed`);
process.exit(fail ? 1 : 0);
